package cmd

import (
	"fmt"
	"io"
	"strings"

	"github.com/spf13/cobra"

	"github.com/rossedman/strata/internal/cli"
	"github.com/rossedman/strata/internal/ecr"
	"github.com/rossedman/strata/internal/render"
	"github.com/rossedman/strata/internal/service"
)

var cleanupLifecycleCmd = &cobra.Command{
	Use:   "lifecycle",
	Short: "Generate ECR lifecycle policies that expire what strata calls abandoned",
	Long: `Generates one ECR lifecycle policy per repo with a rule that expires untagged
images pushed more than abandoned_pull_days ago (from the staleness policy, or
--days), so ECR does the cleanup itself.

ECR sees push age but not pulls or what is built on an image, so each rule is
checked against the index first. A repo where the rule would expire an image
strata keeps (pulled recently, a base other images are built on, or a platform
of a tagged index) gets no policy, and the table says why. --include-conflicts
writes the rule anyway.

-o script prints aws ecr put-lifecycle-policy commands to review and run.
Preview each with aws ecr start-lifecycle-policy-preview before applying it.
A policy replaces any lifecycle policy the repository already has.`,
	Example: `  strata cleanup lifecycle
  strata cleanup lifecycle --repo '*/sandbox/*' --days 30
  strata cleanup lifecycle -o script > apply-lifecycle.sh
  strata cleanup lifecycle -o json`,
	Args: cobra.NoArgs,
	RunE: func(cmd *cobra.Command, _ []string) (err error) {
		v := state.V
		out := v.GetString("output")
		if err := cli.OneOf("output", out, render.Table, render.JSON, "script"); err != nil {
			return err
		}
		svc, release, err := state.Backend(cmd.Context())
		if err != nil {
			return err
		}
		defer cli.Release(release, &err)
		lcs, err := svc.Lifecycles(cmd.Context(), service.LifecycleOptions{
			Repos: v.GetStringSlice("repo"), Days: v.GetInt("days"), IncludeConflicts: v.GetBool("include-conflicts"),
		})
		if err != nil {
			return err
		}
		w := cli.Out(cmd)
		switch out {
		case render.JSON:
			return render.JSONTo(w, lcs)
		case "script":
			return lifecycleScript(w, lcs)
		}
		rows := make([][]any, len(lcs))
		for i, lc := range lcs {
			status := "policy"
			if lc.Policy == nil {
				status = "skipped: " + lc.Skipped
				if len(lc.Conflicts) > 0 {
					status += " (" + lc.Conflicts[0].Reason + ")"
				}
			}
			rows[i] = []any{lc.Repo, int64(lc.Days), int64(lc.Expires), int64(lc.Agree), status}
		}
		return render.WriteRows(w, out, []string{"repo", "days", "would_expire", "agree", "status"}, rows)
	},
}

// lifecycleScript writes a shell script that applies the policies.
func lifecycleScript(w io.Writer, lcs []service.Lifecycle) error {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n# ECR lifecycle policies generated by strata cleanup lifecycle.\n")
	b.WriteString("# Each replaces the repository's current lifecycle policy. Preview first:\n")
	b.WriteString("#   aws ecr start-lifecycle-policy-preview --repository-name <name> --lifecycle-policy-text '<policy>'\nset -eu\n")
	for _, lc := range lcs {
		if lc.Policy == nil {
			fmt.Fprintf(&b, "\n# %s: skipped, %s\n", lc.Repo, lc.Skipped)
			continue
		}
		host, _, _ := strings.Cut(lc.Repo, "/")
		target := ""
		if account, region, ok := ecr.ParseHost(host); ok {
			target = fmt.Sprintf(" --registry-id %s --region %s", account, region)
		}
		fmt.Fprintf(&b, "\n# %s: expires %d untagged image(s) today\naws ecr put-lifecycle-policy%s --repository-name %s --lifecycle-policy-text '%s'\n",
			lc.Repo, lc.Expires, target, lc.Name, lc.Policy.Text())
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// init registers the cleanup lifecycle command and its flags.
func init() {
	lf := cleanupLifecycleCmd.Flags()
	lf.StringSlice("repo", nil, "only repos matching this glob, with the host, such as '*/sandbox/*' (repeatable)")
	lf.Int("days", 0, "expire untagged images pushed more than this many days ago (default: the policy's abandoned_pull_days)")
	lf.Bool("include-conflicts", false, "write a repo's rule even when it would expire images strata keeps")
	lf.StringP("output", "o", "table", "output format: table, json or script")
	cleanupCmd.AddCommand(cleanupLifecycleCmd)
}
